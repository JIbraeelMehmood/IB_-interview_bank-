'use strict';
const fs=require('fs'),path=require('path');
const DIR=path.resolve(__dirname,'..');
const h=fs.readFileSync(path.join(DIR,'interview-box.html'),'utf8');
const m=h.match(/<script[^>]*id=["']bank["'][^>]*>([\s\S]*?)<\/script>/);
const b=JSON.parse(m[1].trim());
const out=[];
out.push('CURRENT EMBEDDED BANK: '+b.length+' records');
out.push('\n--- by src ---');
out.push(JSON.stringify(b.reduce(function(a,x){a[x.src]=(a[x.src]||0)+1;return a;},{}),null,1));
out.push('\n--- by lvl ---');
out.push(JSON.stringify(b.reduce(function(a,x){a[x.lvl]=(a[x.lvl]||0)+1;return a;},{})));
out.push('\n--- by priority ---');
out.push(JSON.stringify(b.reduce(function(a,x){a[x.priority]=(a[x.priority]||0)+1;return a;},{})));
out.push('\n--- tag frequency ---');
const tf={};b.forEach(function(x){(x.t||[]).forEach(function(t){tf[t]=(tf[t]||0)+1;});});
out.push(JSON.stringify(tf,null,1));
function norm(s){return String(s||'').toLowerCase().replace(/^q\d+\.\s*/,'').replace(/[^\p{L}\p{N}\s]/gu,' ').replace(/\s+/g,' ').trim();}
const groups={};b.forEach(function(x){const k=norm(x.q);(groups[k]=groups[k]||[]).push(x.id);});
const dups=Object.keys(groups).filter(function(k){return groups[k].length>1;});
let pairs=0;dups.forEach(function(k){pairs+=groups[k].length-1;});
out.push('\n--- DEDUP by normalized question text ---');
out.push('distinct normalized keys: '+Object.keys(groups).length);
out.push('keys with >1 record: '+dups.length);
out.push('redundant records removable: '+pairs);
out.push('\nexamples:');
dups.slice(0,12).forEach(function(k){out.push('  ['+groups[k].length+'] '+k.slice(0,80)+'  -> '+groups[k].join(', '));});
const idPat={};b.forEach(function(x){const mm=/^q_(\d+)_/.exec(x.id);if(mm){const n=mm[1];(idPat[n]=idPat[n]||[]).push(x.id);}});
const dupNums=Object.keys(idPat).filter(function(n){return idPat[n].length>1;});
out.push('\n--- same Q-number across ids ---');
out.push('Q-numbers appearing in >1 id: '+dupNums.length);
dupNums.slice(0,10).forEach(function(n){out.push('  Q'+n+': '+idPat[n].length+' ids');});
fs.writeFileSync(path.join(DIR,'_audit','compose.txt'),out.join('\n'));
console.log('ok');
