'use strict';
const fs = require('fs');
const path = require('path');
const DIR = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(DIR, 'interview-box.html'), 'utf8');
const m = html.match(/<script[^>]*id=["']bank["'][^>]*>([\s\S]*?)<\/script>/);
if (!m) throw new Error('no bank script');
const parsed = JSON.parse(m[1].trim());
const out = [];
out.push('node: ' + process.version);
out.push('typeof parsed: ' + (Array.isArray(parsed) ? 'array' : typeof parsed));
out.push('top keys: ' + Object.keys(parsed).slice(0, 40).join(','));
out.push('top keys count: ' + Object.keys(parsed).length);
const first = Object.keys(parsed)[0];
out.push('\nfirst key: ' + first);
out.push('first value type: ' + typeof parsed[first]);
out.push('first value (truncated): ' + JSON.stringify(parsed[first]).slice(0, 1200));
out.push('\nraw head of script tag: ' + m[1].trim().slice(0, 400));
fs.writeFileSync(path.join(DIR, '_audit', 'emb0.txt'), out.join('\n'));
console.log('ok');
