'use strict';
const fs=require('fs'),path=require('path');
const DIR=path.resolve(__dirname,'..');
const h=fs.readFileSync(path.join(DIR,'v1-interview-box/interview-box.html'),'utf8');
const m=h.match(/<script[^>]*id=["']bank["'][^>]*>([\s\S]*?)<\/script>/);
const b=JSON.parse(m[1].trim());
let fill=0,fillX1=0,noFillX1=0,x0fill=0;
b.forEach(function(x){const has=/class="fill"/.test(String(x.a));if(has)fill++;if(has&&x.x===1)fillX1++;if(!has&&x.x===1)noFillX1++;if(has&&x.x===0)x0fill++;});
console.log('records with class="fill" in answer: '+fill);
console.log('  of those x=1: '+fillX1);
console.log('  of those x=0: '+x0fill);
console.log('x=1 but no fill span: '+noFillX1);
console.log('total x=1: '+b.filter(function(x){return x.x===1;}).length);
fs.writeFileSync(path.join(DIR,'_audit','xfill.txt'),['fill='+fill,'fill&x1='+fillX1,'fill&x0='+x0fill,'x1_total='+b.filter(function(x){return x.x===1;}).length].join('\n'));
