'use strict';
const fs=require('fs'),path=require('path');
const DIR=path.resolve(__dirname,'..');
const h=fs.readFileSync(path.join(DIR,'interview-box.html'),'utf8');
const m=h.match(/<script[^>]*id=["']bank["'][^>]*>([\s\S]*?)<\/script>/);
const bank=JSON.parse(m[1].trim());
const app=h.slice(0,m.index)+h.slice(m.index+m[0].length);
const out=[];
function count(re,label){const n=(app.match(re)||[]).length;out.push(label+': '+n+' occurrence(s) in app code');}
out.push('=== Does app code read the new-schema fields? ===');
count(/\.lvl\b/g,'o.lvl');
count(/\.priority\b/g,'o.priority');
count(/\.src\b/g,'o.src');
count(/\.tr\b/g,'o.tr');
count(/\.ex\b/g,'o.ex');
count(/\.x\b/g,'o.x');
count(/\.f\b/g,'o.f');
count(/\.p\b/g,'o.p');
out.push('\n=== mkQ projection on current bank ===');
function mkQ(o){return {id:o.id,q:o.q,a:o.a,l:o.l||'m',p:o.p||'',c:o.c||'',f:o.f||'',t0:o.t||[],s:o.s||'b',x:o.x||0};}
const proj=bank.map(mkQ);
const dist=(key)=>{const d={};proj.forEach(function(q){d[String(q[key])]=(d[String(q[key])]||0)+1;});return d;};
out.push('l  -> '+JSON.stringify(dist('l')));
out.push('p  -> '+JSON.stringify(dist('p')));
out.push('c  -> '+JSON.stringify(dist('c')));
out.push('f  -> '+JSON.stringify(dist('f')));
out.push('s  -> '+JSON.stringify(dist('s')));
out.push('x  -> '+JSON.stringify(dist('x')));
out.push('t0 empty count: '+proj.filter(function(q){return !q.t0.length;}).length);
out.push('\n=== q.raw presence (needed by src/imp filters) ===');
out.push('built-in bank items get q.raw? NO — q.raw only set for S.my / S.ai');
out.push('\n=== PARTS_BOOK / PARTS_NEW build ===');
var pb={},pn={};bank.forEach(function(o){(o.s==='n'?pn:pb)[o.p]=1;});
out.push('PARTS_BOOK = '+JSON.stringify(Object.keys(pb)));
out.push('PARTS_NEW  = '+JSON.stringify(Object.keys(pn)));
out.push('\n=== level filter (LV) ===');
out.push('LV={j:Basic,m:Mid,s:Senior} -> all 531 render as "Mid"');
out.push('\n=== question text still carries source numbering ===');
out.push('sample q: '+JSON.stringify(bank[0].q));
out.push('q starting with Q<number>. : '+bank.filter(function(x){return /^Q\d+\./.test(x.q);}).length);
fs.writeFileSync(path.join(DIR,'_audit','mismatch.txt'),out.join('\n'));
console.log(out.join('\n'));
