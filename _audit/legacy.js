'use strict';
const fs=require('fs'),path=require('path');
const DIR=path.resolve(__dirname,'..');
const h=fs.readFileSync(path.join(DIR,'v1-interview-box/interview-box.html'),'utf8');
const m=h.match(/<script[^>]*id=["']bank["'][^>]*>([\s\S]*?)<\/script>/);
const b=JSON.parse(m[1].trim());
const out=[];
out.push('v1 bank count='+b.length);
const dist={};b.forEach(function(x){Object.keys(x).forEach(function(k){dist[k]=(dist[k]||0)+1;});});
out.push('key counts: '+JSON.stringify(dist));
out.push('\n--- values of l ---');out.push(JSON.stringify(b.reduce(function(a,x){a[x.l]=(a[x.l]||0)+1;return a;},{})));
out.push('\n--- values of s ---');out.push(JSON.stringify(b.reduce(function(a,x){a[x.s]=(a[x.s]||0)+1;return a;},{})));
out.push('\n--- values of x ---');out.push(JSON.stringify(b.reduce(function(a,x){a[String(x.x)]=(a[String(x.x)]||0)+1;return a;},{})));
out.push('\n--- values of p (parts) ---');out.push(JSON.stringify(b.reduce(function(a,x){a[x.p]=(a[x.p]||0)+1;return a;},{}),null,1));
out.push('\n--- values of c (cat) ---');out.push(JSON.stringify(b.reduce(function(a,x){a[x.c]=(a[x.c]||0)+1;return a;},{}),null,1));
out.push('\n--- values of f (flags) ---');out.push(JSON.stringify(b.reduce(function(a,x){a[x.f]=(a[x.f]||0)+1;return a;},{}),null,1));
out.push('\n--- f char usage ---');
const fc={};b.forEach(function(x){String(x.f||'').split('').forEach(function(c){fc[c]=(fc[c]||0)+1;});});
out.push(JSON.stringify(fc));
out.push('\n--- sample with tr ---');
b.filter(function(x){return x.tr;}).slice(0,3).forEach(function(x){out.push(JSON.stringify(x,null,1).slice(0,900));});
out.push('\n--- sample with ex ---');
b.filter(function(x){return x.ex;}).slice(0,3).forEach(function(x){out.push(JSON.stringify(x,null,1).slice(0,900));});
out.push('\n--- sample with x>0 ---');
b.filter(function(x){return x.x;}).slice(0,3).forEach(function(x){out.push(JSON.stringify(x,null,1).slice(0,700));});
out.push('\n--- first 2 records ---');
out.push(JSON.stringify(b.slice(0,2),null,1).slice(0,1200));
fs.writeFileSync(path.join(DIR,'_audit','legacy.txt'),out.join('\n'));
console.log('ok');
