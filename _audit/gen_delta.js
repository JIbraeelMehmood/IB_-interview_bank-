'use strict';
const fs=require('fs'),path=require('path');
const DIR=path.resolve(__dirname,'..');
function split(file){const h=fs.readFileSync(path.join(DIR,file),'utf8');const m=h.match(/<script[^>]*id=["']bank["'][^>]*>([\s\S]*?)<\/script>/);return{head:h.slice(0,m.index),bank:m[1],tail:h.slice(m.index+m[0].length)};}
const cur=split('interview-box.html'),v1=split('v1-interview-box/interview-box.html');
function keysOf(arr){const s={};arr.forEach(function(x){Object.keys(x).forEach(function(k){s[k]=(s[k]||0)+1});});return s;}
const out=[];
out.push('CUR bank isArray='+Array.isArray(cur.bank.trim()[0]));
const cb=JSON.parse(cur.bank.trim());
const vb=JSON.parse(v1.bank.trim());
out.push('cur bank type='+Object.prototype.toString.call(cb)+' count='+(cb.length||Object.keys(cb).length));
out.push('v1  bank type='+Object.prototype.toString.call(vb)+' count='+(vb.length||Object.keys(vb).length));
const cArr=Array.isArray(cb)?cb:Object.keys(cb).map(function(k){return cb[k];});
const vArr=Array.isArray(vb)?vb:Object.keys(vb).map(function(k){return vb[k];});
out.push('\n=== CUR bank keys (key:count) ===');
out.push(JSON.stringify(keysOf(cArr),null,1));
out.push('\n=== V1 bank keys (key:count) ===');
out.push(JSON.stringify(keysOf(vArr),null,1));
out.push('\n=== CUR sample[0] ===');
out.push(JSON.stringify(cArr[0],null,1).slice(0,1200));
out.push('\n=== CUR ids first 15 ===');
out.push(cArr.slice(0,15).map(function(x){return x.id;}).join(', '));
out.push('\n=== CUR ids last 15 ===');
out.push(cArr.slice(-15).map(function(x){return x.id;}).join(', '));
out.push('\n=== CUR duplicate ids ===');
const seen={},dups=[];cArr.forEach(function(x){if(seen[x.id])dups.push(x.id);seen[x.id]=1;});
out.push('dup id count='+dups.length+' -> '+dups.slice(0,40).join(', '));
out.push('\n=== V1 ids first 10 ===');
out.push(vArr.slice(0,10).map(function(x){return x.id;}).join(', '));
out.push('\n=== CUR s values ===');
out.push(JSON.stringify(cArr.reduce(function(a,x){a[x.s]=(a[x.s]||0)+1;return a;},{})));
out.push('\n=== CUR l values ===');
out.push(JSON.stringify(cArr.reduce(function(a,x){a[x.l]=(a[x.l]||0)+1;return a;},{})));
out.push('\n=== CUR f values ===');
out.push(JSON.stringify(cArr.reduce(function(a,x){a[x.f]=(a[x.f]||0)+1;return a;},{})));
out.push('\n=== CUR p values (top 40) ===');
out.push(JSON.stringify(cArr.reduce(function(a,x){a[x.p]=(a[x.p]||0)+1;return a;},{}),null,1).slice(0,3000));
fs.writeFileSync(path.join(DIR,'_audit','delta.txt'),out.join('\n'));
fs.writeFileSync(path.join(DIR,'_audit','cur.head'),cur.head);
fs.writeFileSync(path.join(DIR,'_audit','v1.head'),v1.head);
fs.writeFileSync(path.join(DIR,'_audit','cur.tail'),cur.tail);
fs.writeFileSync(path.join(DIR,'_audit','v1.tail'),v1.tail);
