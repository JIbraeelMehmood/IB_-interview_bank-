'use strict';
const fs=require('fs'),path=require('path');
const DIR=path.resolve(__dirname,'..');
const cl=JSON.parse(fs.readFileSync(path.join(DIR,'interview-box-banks-clean.json'),'utf8'));
const out=[];
out.push('version='+cl.version+'  total='+cl.total+'  generated='+cl.generated);
out.push('\n=== files meta (pre-dedup counts written by importer) ===');
Object.keys(cl.files).forEach(function(k){out.push('  '+cl.files[k]+'  '+k);});
const actual={};cl.questions.forEach(function(q){actual[q.src]=(actual[q.src]||0)+1;});
out.push('\n=== ACTUAL src counts on questions (post-dedup) ===');
Object.keys(actual).forEach(function(k){out.push('  '+actual[k]+'  '+k);});
out.push('\n=== files-meta keys with NO matching question src ===');
Object.keys(cl.files).forEach(function(k){ if(!(k in actual)) out.push('  '+k); });
out.push('\n=== question src values with NO files-meta entry ===');
Object.keys(actual).forEach(function(k){ if(!(k in cl.files)) out.push('  '+k+' ('+actual[k]+')'); });
out.push('\n=== does the Answers-2 file exist on disk? ===');
const f2='Senior PHP Laravel Interview 5 Server Questions + Top 25 (Roman Urdu Answers-2.md';
out.push('  as imported (no closing paren): '+fs.existsSync(path.join(DIR,f2)));
const f2b='Senior PHP Laravel Interview 5 Server Questions + Top 25 (Roman Urdu Answers-2.md';
out.push('  with closing paren: '+fs.existsSync(path.join(DIR,f2b)));
out.push('\n=== id uniqueness + priority/lvl/s sanity ===');
out.push('  total='+cl.questions.length+'  unique ids='+new Set(cl.questions.map(function(q){return q.id;})).size);
const lv={},pr={},s={};cl.questions.forEach(function(q){lv[q.lvl]=(lv[q.lvl]||0)+1;pr[q.priority]=(pr[q.priority]||0)+1;s[q.s]=(s[q.s]||0)+1;});
out.push('  lvl: '+JSON.stringify(lv));
out.push('  priority: '+JSON.stringify(pr));
out.push('  s: '+JSON.stringify(s));
fs.writeFileSync(path.join(DIR,'_audit','meta.txt'),out.join('\n'));
console.log(out.join('\n'));
