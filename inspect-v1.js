'use strict';
const fs = require('fs');
const path = require('path');
const DIR = __dirname;
const h = fs.readFileSync(path.join(DIR, 'v1-interview-box', 'interview-box.html'), 'utf8');
const m = h.match(/<script[^>]*id=["']bank["'][^>]*>([\s\S]*?)<\/script>/);
if (!m) { console.log('NO BANK TAG'); process.exit(0); }
const j = JSON.parse(m[1]);
console.log('count', j.length);
const keys = new Set();
j.forEach(o => Object.keys(o).forEach(k => keys.add(k)));
console.log('all keys', [...keys]);
const cats = {}, lv = {}, src = {}, flags = {};
j.forEach(o => {
  cats[o.p] = (cats[o.p] || 0) + 1;
  lv[o.l] = (lv[o.l] || 0) + 1;
  src[o.s] = (src[o.s] || 0) + 1;
  flags[o.f] = (flags[o.f] || 0) + 1;
});
console.log('levels', lv);
console.log('src', src);
console.log('flags', flags);
console.log('cats', cats);
console.log('has tr count', j.filter(o => o.tr).length);
console.log('--- sample records ---');
j.slice(0, 2).forEach(o => console.log(JSON.stringify(o, null, 1).slice(0, 1400)));
const withTr = j.find(o => o.tr);
if (withTr) console.log('--- tr sample ---', JSON.stringify(withTr, null, 1).slice(0, 1500));
console.log('--- id samples ---', j.slice(0, 6).map(o => o.id), '...', j.slice(-6).map(o => o.id));
console.log('unique ids', new Set(j.map(o => o.id)).size);
console.log('=== tr samples ===');
j.filter(o => o.tr).slice(0, 3).forEach(o => console.log(JSON.stringify(o, null, 1).slice(0, 2200)));
console.log('=== tr key structure ===');
const trKeys = new Set();
j.filter(o => o.tr).forEach(o => Object.keys(o.tr).forEach(k => trKeys.add(k)));
console.log('tr langs', [...trKeys]);
const tk = new Set();
j.filter(o => o.tr).forEach(o => Object.values(o.tr).forEach(t => Object.keys(t || {}).forEach(k => tk.add(k))));
console.log('tr fields', [...tk]);
console.log('=== x / ex ===');
console.log('has x:', j.filter(o => o.x).length, 'has ex:', j.filter(o => o.ex).length);
const wx = j.find(o => o.x); if (wx) console.log(JSON.stringify(wx, null, 1).slice(0, 900));
const we = j.find(o => o.ex); if (we) console.log(JSON.stringify(we, null, 1).slice(0, 900));
